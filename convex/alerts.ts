import { query, mutation } from "./_generated/server";
import { v } from "convex/values";

const DEFAULT_LAT = 10.8247;
const DEFAULT_LNG = 78.6956;

/** Unique 8-hex event id (fits compact BLE Event State layout; 0 is reserved). */
function generateEventId(): string {
  const bytes = new Uint8Array(4);
  if (typeof crypto !== "undefined" && crypto.getRandomValues) {
    crypto.getRandomValues(bytes);
  } else {
    for (let i = 0; i < 4; i++) bytes[i] = Math.floor(Math.random() * 256);
  }
  if (bytes.every((b) => b === 0)) bytes[0] = 1;
  return Array.from(bytes)
    .map((b) => b.toString(16).padStart(2, "0"))
    .join("");
}

export const getActiveAlert = query({
  args: {},
  handler: async (ctx) => {
    return await ctx.db.query("active_alert").unique();
  },
});

export const getAlertByEventId = query({
  args: { eventId: v.string() },
  handler: async (ctx, args) => {
    const eventKey = args.eventId.toLowerCase();
    return await ctx.db
      .query("active_alert")
      .withIndex("by_event_id", (q) => q.eq("event_id", eventKey))
      .unique();
  },
});

export const triggerAlert = mutation({
  args: {
    userId: v.id("users"),
    latitude: v.optional(v.float64()),
    longitude: v.optional(v.float64()),
    beaconId: v.optional(v.string()),
    /** Optional id generated by the beacon hardware (button press). */
    eventId: v.optional(v.string()),
  },
  handler: async (ctx, args) => {
    const latitude = args.latitude ?? DEFAULT_LAT;
    const longitude = args.longitude ?? DEFAULT_LNG;
    const timestamp = new Date().toLocaleTimeString("en-US", {
      hour: "2-digit",
      minute: "2-digit",
    });
    const eventId = (args.eventId ?? generateEventId()).toLowerCase();
    const beaconId = args.beaconId ?? "ESP32-S3";

    const existing = await ctx.db.query("active_alert").unique();
    if (existing) {
      await ctx.db.patch(existing._id, {
        is_active: true,
        beacon_id: beaconId,
        event_id: eventId,
        ble_mode: "e",
        detected_at: timestamp,
        latitude,
        longitude,
        contacts_dispatched: 0,
        dispatch_url: `/track/${eventId}`,
      });
    } else {
      await ctx.db.insert("active_alert", {
        user_id: args.userId,
        beacon_id: beaconId,
        event_id: eventId,
        ble_mode: "e",
        is_active: true,
        detected_at: timestamp,
        signal_dbm: "-45 dBm (Good)",
        latitude,
        longitude,
        contacts_dispatched: 0,
        dispatch_url: `/track/${eventId}`,
      });
    }

    const newAlertId = await ctx.db.insert("alert_history", {
      user_id: args.userId,
      beacon_id: undefined,
      event_type: "SOS_ALERT",
      status_badge: "Alert Sent",
      latitude,
      longitude,
      created_at: `Today, ${timestamp}`,
    });

    const contactCount = await ctx.db
      .query("emergency_contacts")
      .filter((q) => q.eq(q.field("user_id"), args.userId))
      .collect();

    await ctx.db.insert("notifications", {
      user_id: args.userId,
      type: "SOS",
      title: "Emergency Distress Broadcasted",
      message: `SOS coordinates (${latitude.toFixed(4)}, ${longitude.toFixed(4)}) transmitted to ${contactCount.length} emergency contacts and police dispatch. Event ${eventId}. Live tracking link: /track/${eventId}`,
      is_read: false,
      created_at: `Today, ${timestamp}`,
    });

    return { historyId: newAlertId, eventId, beaconId };
  },
});

export const cancelAlert = mutation({
  args: {
    userId: v.id("users"),
    /**
     * Event id from the active SOS. Must match the open event so
     * cancellation cannot close a different activation.
     */
    eventId: v.optional(v.string()),
    /** True when the app verified this event over GATT before cancelling. */
    bleVerified: v.optional(v.boolean()),
    beaconId: v.optional(v.string()),
  },
  handler: async (ctx, args) => {
    const existing = await ctx.db.query("active_alert").unique();
    if (!existing || !existing.is_active) return { cancelled: false, reason: "no-active-alert" };

    if (args.eventId && existing.event_id) {
      const requested = args.eventId.toLowerCase();
      if (existing.event_id.toLowerCase() !== requested) {
        return {
          cancelled: false,
          reason: "event-id-mismatch",
          activeEventId: existing.event_id,
        };
      }
    }

    await ctx.db.patch(existing._id, {
      is_active: false,
      ble_mode: "c",
      ...(args.beaconId ? { beacon_id: args.beaconId } : {}),
    });

    await ctx.db.insert("alert_history", {
      user_id: args.userId,
      beacon_id: undefined,
      event_type: "SYSTEM_UPDATE",
      status_badge: "Warning",
      latitude: existing.latitude,
      longitude: existing.longitude,
      created_at: "Just now",
    });

    const verifyNote = args.bleVerified
      ? "Beacon GATT confirmed the event ID."
      : "Cancelled from app without GATT confirmation.";

    await ctx.db.insert("notifications", {
      user_id: args.userId,
      type: "SYSTEM",
      title: "SOS Alert Cancelled by User",
      message: `False alert notice dispatched to emergency contacts for event ${existing.event_id}. Emergency routing standby resumed. ${verifyNote}`,
      is_read: false,
      created_at: "Just now",
    });

    return {
      cancelled: true,
      eventId: existing.event_id,
      bleVerified: Boolean(args.bleVerified),
    };
  },
});

export const getAlertHistory = query({
  args: { userId: v.id("users"), filter: v.optional(v.string()) },
  handler: async (ctx, args) => {
    const query = ctx.db.query("alert_history").filter((q) =>
      q.eq(q.field("user_id"), args.userId)
    );

    const results = await query.order("desc").collect();

    if (!args.filter || args.filter === "ALL") return results;
    if (args.filter === "SOS") {
      return results.filter(
        (a) => a.event_type === "SOS_ALERT" || a.event_type === "CONTACT_DELIVERED"
      );
    }
    if (args.filter === "SYSTEM") {
      return results.filter(
        (a) => a.event_type === "BEACON_CONNECTED" || a.event_type === "LOW_BATTERY"
      );
    }
    if (args.filter === "UPDATES") {
      return results.filter((a) => a.event_type === "SYSTEM_UPDATE");
    }
    return results;
  },
});
